-- object: idpaas.device | type: TABLE --
-- DROP TABLE IF EXISTS idpaas.device CASCADE;
CREATE TABLE idpaas.device(
	device_id character varying(64) NOT NULL,
	jkt character varying(64) NOT NULL,
	public_key_jwk jsonb NOT NULL,
	app_attest_key_id character varying(128),
	platform character varying(16) NOT NULL,
	os_version character varying(32) NOT NULL,
	manufacturer character varying(64),
	model character varying(128) NOT NULL,
	app_version character varying(32) NOT NULL,
	policy_version character varying(64),
	attestation_summary jsonb NOT NULL DEFAULT '{}'::jsonb,
	status_code character varying(16) NOT NULL DEFAULT 'ACTIVE',
	revoked_dtimes timestamp,
	revoked_reason character varying(64),
	cr_by character varying(256) NOT NULL,
	cr_dtimes timestamp NOT NULL,
	upd_by character varying(256),
	upd_dtimes timestamp,
	CONSTRAINT pk_device PRIMARY KEY (device_id),
	-- B1: the same device key can't be registered twice, even by simultaneous requests.
	CONSTRAINT uk_device_jkt UNIQUE (jkt),
	CONSTRAINT ck_device_platform CHECK (platform IN ('android', 'ios')),
	-- iOS devices are identified by the App Attest key ID as well; Android has none.
	CONSTRAINT ck_device_attest_key CHECK ((platform = 'ios') = (app_attest_key_id IS NOT NULL)),
	CONSTRAINT ck_device_os_version CHECK (os_version ~ '^[0-9]+(\.[0-9]+)*$'),
	CONSTRAINT ck_device_attestation_summary CHECK (jsonb_typeof(attestation_summary) = 'object'),
	CONSTRAINT ck_device_public_key CHECK (jsonb_typeof(public_key_jwk) = 'object'),
	CONSTRAINT ck_device_status CHECK (status_code IN ('ACTIVE', 'REVOKED')),
	CONSTRAINT ck_device_revoked CHECK ((status_code = 'REVOKED') = (revoked_dtimes IS NOT NULL)),
	-- A revoked key always says why, so support can't leave it blank.
	CONSTRAINT ck_device_revoked_reason CHECK (status_code <> 'REVOKED' OR revoked_reason IS NOT NULL),
	-- RFC 7638 SHA-256 thumbprint, base64url without padding: always 43 characters. Stops a thumbprint in another
	-- encoding (hex, padded base64) from slipping past the uniqueness rule.
	CONSTRAINT ck_device_jkt CHECK (jkt ~ '^[A-Za-z0-9_-]{43}$')

);
-- ddl-end --
-- B1: the same iOS App Attest key can't be registered twice. NULLs (Android) don't collide.
CREATE UNIQUE INDEX uk_device_attest_key ON idpaas.device USING btree (app_attest_key_id) WHERE app_attest_key_id IS NOT NULL;
