-- object: idpaas.fn_device_before_update | type: FUNCTION --
-- A device is registered once and can only be revoked, never changed back. Whoever makes the change, the
-- trigger (not the caller) fills in who and when, so the audit columns can't be left empty or faked:
--   UPDATE idpaas.device SET status_code = 'REVOKED', revoked_reason = 'FRAUD_SUSPECTED' WHERE device_id = '...';
-- A revoked row is final: no edit and no ACTIVE again. If product wants an undo, the phone registers a new key.
CREATE OR REPLACE FUNCTION idpaas.fn_device_before_update() RETURNS trigger AS $$
BEGIN
	IF OLD.status_code = 'REVOKED' THEN
		RAISE EXCEPTION 'idpaas.device: device % is revoked and can not be changed; register a new key instead', OLD.device_id;
	END IF;
	-- What was reported and attested at registration stays as it was; only the status and reason change.
	IF (NEW.device_id, NEW.jkt, NEW.public_key_jwk, NEW.app_attest_key_id, NEW.platform, NEW.os_version,
		NEW.manufacturer, NEW.model, NEW.app_version, NEW.policy_version, NEW.attestation_summary,
		NEW.cr_by, NEW.cr_dtimes)
		IS DISTINCT FROM
		(OLD.device_id, OLD.jkt, OLD.public_key_jwk, OLD.app_attest_key_id, OLD.platform, OLD.os_version,
		OLD.manufacturer, OLD.model, OLD.app_version, OLD.policy_version, OLD.attestation_summary,
		OLD.cr_by, OLD.cr_dtimes) THEN
		RAISE EXCEPTION 'idpaas.device: only status_code and revoked_reason can be changed (device %)', OLD.device_id;
	END IF;
	NEW.upd_by := session_user;
	NEW.upd_dtimes := (now() AT TIME ZONE 'UTC');
	IF NEW.status_code = 'REVOKED' THEN
		NEW.revoked_dtimes := (now() AT TIME ZONE 'UTC');
	ELSE
		NEW.revoked_dtimes := NULL;
		NEW.revoked_reason := NULL;
	END IF;
	RETURN NEW;
END;
$$ LANGUAGE plpgsql;
-- ddl-end --

-- object: trg_device_before_update | type: TRIGGER --
CREATE TRIGGER trg_device_before_update
	BEFORE UPDATE ON idpaas.device
	FOR EACH ROW EXECUTE FUNCTION idpaas.fn_device_before_update();
-- ddl-end --

